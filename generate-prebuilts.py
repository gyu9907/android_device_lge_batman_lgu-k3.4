"""Generate Android 12 blob modules, adapted from ef52 commit 8a13098."""
import argparse
import json
from pathlib import Path, PurePosixPath
import re
import struct


def generate(vendor):
    device = Path(__file__).resolve().parent
    link_libraries = "liboncrpc libnv libaudioalsa libacdbloader libacdbmapper libstlport libgps.utils libaudcal libdsm libqueue libdiag libgsl".split()
    skipped = {"lib/" + name + ".so" for name in link_libraries}
    skipped.update({"lib/libtime_genoff.so", "lib/egl/libEGL_adreno200.so",
                    "lib/egl/libGLESv2_adreno200.so", "vendor/firmware/libpn544_fw.so"})
    packages = link_libraries + ["libpn544_fw"]
    modules, copies, destinations = [], [], set()
    for line in (device / "proprietary-files.txt").read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        paths = line.split("|", 1)[0].split(":", 1)
        source = paths[0]
        if source in skipped:
            continue
        destination = paths[-1]
        if len(paths) == 1 and source in {"lib/hw/camera.msm8660.so", "lib/hw/sensors.msm8660.so"}:
            destination = source.replace(".msm8660.so", ".vendor.msm8660.so")
        if destination in destinations:
            raise ValueError("Duplicate destination: " + destination)
        destinations.add(destination)
        blob = vendor / "proprietary" / source
        with blob.open("rb") as stream:
            header = stream.read(20)
        is_vendor = destination.startswith("vendor/")
        relative = destination.removeprefix("vendor/")
        native = relative.startswith(("bin/", "lib/"))
        if header[:4] != b"\x7fELF" or not native:
            copies.append(f"vendor/lge/batman_lgu/proprietary/{source}:system/{destination}")
            continue
        if header[4:6] != b"\x01\x01" or struct.unpack_from("<H", header, 18)[0] != 40:
            raise ValueError("Expected ARM ELF32: " + str(blob))
        binary = relative.startswith("bin/")
        install = PurePosixPath(relative).relative_to("bin" if binary else "lib")
        if not binary and not install.name.endswith(".so"):
            raise ValueError("Expected shared library: " + destination)
        name = "batman_blob_" + re.sub(r"[^a-zA-Z0-9_]", "_", destination)
        kind = "cc_prebuilt_binary" if binary else "cc_prebuilt_library_shared"
        lines = [kind + " {", f"    name: {json.dumps(name)},",
                 '    defaults: ["batman_blob_defaults"],',
                 f"    stem: {json.dumps(install.name if binary else install.name[:-3])},",
                 "    arch: { arm: { enabled: true, srcs: [" + json.dumps("proprietary/" + source) + "] } },"]
        if is_vendor:
            lines.append("    vendor: true,")
        if str(install.parent) != ".":
            lines.append(f"    relative_install_path: {json.dumps(str(install.parent))},")
        lines.append("}")
        modules.append("\n".join(lines))
        packages.append(name)

    bp = '''// Generated by device/lge/batman_lgu/generate-prebuilts.py.
// SPDX-License-Identifier: Apache-2.0
soong_namespace {}

cc_defaults {
    name: "batman_blob_defaults",
    compile_multilib: "32",
    enabled: false,
    strip: { none: true },
    // As on ef52, these runtime-loaded blobs use private legacy ABI and shims.
    // Keep bytes and installation paths; linkable libraries remain in Android.mk.
    check_elf_files: false,
    system_shared_libs: [],
    stl: "none",
}

filegroup {
    name: "batman_pn544_firmware",
    srcs: ["proprietary/vendor/firmware/libpn544_fw.so"],
}
'''
    mk = "# Generated by device/lge/batman_lgu/generate-prebuilts.py.\n"
    mk += "PRODUCT_SOONG_NAMESPACES += vendor/lge/batman_lgu\n\n"
    for variable, values in [("PRODUCT_PACKAGES", packages), ("PRODUCT_COPY_FILES", copies)]:
        mk += variable + " += \\\n    " + " \\\n    ".join(values) + "\n\n"
    # Validate the entire manifest before replacing either generated file.
    (vendor / "Android.bp").write_text(bp + "\n" + "\n\n".join(modules) + "\n")
    (vendor / "batman_lgu-vendor-blobs.mk").write_text(mk.rstrip() + "\n")
    print(f"{len(modules)} native modules, {len(copies)} data/firmware/payload copies")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("vendor", type=Path)
    generate(parser.parse_args().vendor)
